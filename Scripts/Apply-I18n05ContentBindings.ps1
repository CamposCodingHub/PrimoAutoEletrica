$attrs = @('Text','Content','Header','ToolTip','Title')
$files = Get-ChildItem $xamlRoot -Recurse -Filter *.xaml | Where-Object { $_.FullName -notmatch '\\(bin|obj)\\' }
$replacements = 0
$touched = New-Object System.Collections.Generic.List[string]
$log = New-Object System.Collections.Generic.List[object]

foreach ($f in $files) {
    $text = [System.IO.File]::ReadAllText($f.FullName)
    $orig = $text
    foreach ($attr in $attrs) {
        foreach ($kv in $map.GetEnumerator()) {
            $lit = $kv.Key
            $key = $kv.Value
            $escaped = [regex]::Escape($lit)
            $pattern = '(' + $attr + ')="' + $escaped + '"'
            $binding = '$1="{Binding Source={StaticResource LocalizationHelper}, Path=[' + $key + ']}"'
            $matches = [regex]::Matches($text, $pattern)
            if ($matches.Count -gt 0) {
                $text = [regex]::Replace($text, $pattern, $binding)
                $replacements += $matches.Count
                $log.Add([pscustomobject]@{
                    File = $f.FullName.Substring($xamlRoot.Length).TrimStart('\')
                    Literal = $lit
                    Key = $key
                    Count = $matches.Count
                })
            }
        }
    }
    if ($text -ne $orig) {
        $touched.Add($f.FullName.Substring($xamlRoot.Length).TrimStart('\'))
        if (-not $WhatIf) {
            $utf8 = New-Object System.Text.UTF8Encoding $false
            [System.IO.File]::WriteAllText($f.FullName, $text, $utf8)
        }
    }
}

$outDir = Join-Path $root 'TestResults\I18n'
New-Item -ItemType Directory -Path $outDir -Force | Out-Null
$stamp = Get-Date -Format 'yyyyMMdd-HHmmss'
$log | Export-Csv (Join-Path $outDir "i18n05-bindings-$stamp.csv") -NoTypeInformation -Encoding UTF8
Write-Host "Map size: $($map.Count)"
Write-Host "Files touched: $($touched.Count)"
Write-Host "Literal replacements: $replacements"
Write-Host "WhatIf: $WhatIf"
$touched | Select-Object -First 50
